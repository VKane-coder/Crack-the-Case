-- Content: specialties, rubrics and cases. Published versions are immutable so past assessments never change.

create table public.specialties (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null,
  colour_token text not null default 'brand-blue',
  icon text,
  sort_order int not null default 0
);

-- Rubrics -------------------------------------------------------------------

create table public.rubrics (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid references public.organizations (id) on delete cascade,
  name text not null,
  station_type public.station_type not null default 'history',
  current_version_id uuid,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.rubric_versions (
  id uuid primary key default gen_random_uuid(),
  rubric_id uuid not null references public.rubrics (id) on delete cascade,
  version int not null check (version >= 1),
  domain_weights jsonb not null,
  global_rating_descriptors jsonb not null default '{}',
  examiner_question_bank jsonb not null default '[]',
  pass_mark numeric(5, 2) not null default 50 check (pass_mark between 0 and 100),
  locked_at timestamptz,             -- set when a published case version uses it
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  unique (rubric_id, version)
);

alter table public.rubrics
  add constraint rubrics_current_version_fk
  foreign key (current_version_id) references public.rubric_versions (id) on delete set null;

create table public.rubric_items (
  id uuid primary key default gen_random_uuid(),
  rubric_version_id uuid not null references public.rubric_versions (id) on delete cascade,
  key text not null check (key ~ '^[a-z0-9_]+$'),
  domain public.rubric_domain not null,
  label text not null,
  description text,
  max_points numeric(5, 2) not null check (max_points > 0),
  linked_fact_ids text[] not null default '{}',
  is_critical boolean not null default false,
  sort_order int not null default 0,
  unique (rubric_version_id, key)
);

create index rubric_items_version_domain_idx on public.rubric_items (rubric_version_id, domain);

-- Cases ---------------------------------------------------------------------

create table public.cases (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid references public.organizations (id) on delete cascade, -- null = global library
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  title text not null,
  specialty_id uuid not null references public.specialties (id),
  difficulty smallint not null check (difficulty between 1 and 5),
  tags text[] not null default '{}',
  status public.case_status not null default 'draft',
  current_version_id uuid,
  search tsvector,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.case_versions (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references public.cases (id) on delete cascade,
  version int not null check (version >= 1),
  content jsonb not null,            -- full CaseContent (examiner view)
  patient_view jsonb,                -- allow-listed projection, generated by the app before publish
  rubric_version_id uuid not null references public.rubric_versions (id),
  content_hash text not null,
  published_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  unique (case_id, version)
);

alter table public.cases
  add constraint cases_current_version_fk
  foreign key (current_version_id) references public.case_versions (id) on delete set null;

create index cases_catalog_idx on public.cases (status, specialty_id, difficulty);
create index cases_org_idx on public.cases (organization_id) where organization_id is not null;
create index cases_search_idx on public.cases using gin (search);
create index case_versions_case_idx on public.case_versions (case_id);

create trigger rubrics_updated_at before update on public.rubrics
  for each row execute function public.set_updated_at();
create trigger cases_updated_at before update on public.cases
  for each row execute function public.set_updated_at();

create function public.cases_update_search()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.search :=
    setweight(to_tsvector('english', coalesce(new.title, '')), 'A') ||
    setweight(to_tsvector('english', array_to_string(new.tags, ' ')), 'B') ||
    setweight(to_tsvector('english', coalesce((select s.name from public.specialties s where s.id = new.specialty_id), '')), 'C');
  return new;
end;
$$;

create trigger cases_update_search before insert or update of title, tags, specialty_id on public.cases
  for each row execute function public.cases_update_search();

-- Immutability ----------------------------------------------------------------

create function public.case_versions_immutable()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.published_at is not null then
      raise exception 'published case versions cannot be deleted' using errcode = '42501';
    end if;
    return old;
  end if;

  if old.published_at is not null and (
       new.content is distinct from old.content
    or new.patient_view is distinct from old.patient_view
    or new.rubric_version_id is distinct from old.rubric_version_id
    or new.content_hash is distinct from old.content_hash
    or new.published_at is distinct from old.published_at
    or new.case_id is distinct from old.case_id
    or new.version is distinct from old.version
  ) then
    raise exception 'published case versions are immutable; create a new version' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger case_versions_immutable before update or delete on public.case_versions
  for each row execute function public.case_versions_immutable();

create function public.rubric_versions_immutable()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.locked_at is not null then
      raise exception 'locked rubric versions cannot be deleted' using errcode = '42501';
    end if;
    return old;
  end if;
  if old.locked_at is not null and (to_jsonb(new) - 'locked_at') is distinct from (to_jsonb(old) - 'locked_at') then
    raise exception 'locked rubric versions are immutable; create a new version' using errcode = '42501';
  end if;
  if old.locked_at is not null and new.locked_at is null then
    raise exception 'rubric versions cannot be unlocked' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger rubric_versions_immutable before update or delete on public.rubric_versions
  for each row execute function public.rubric_versions_immutable();

create function public.rubric_items_immutable()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_version_id uuid := coalesce(new.rubric_version_id, old.rubric_version_id);
begin
  if exists (select 1 from public.rubric_versions where id = v_version_id and locked_at is not null)
     or (tg_op = 'UPDATE' and exists (select 1 from public.rubric_versions where id = old.rubric_version_id and locked_at is not null)) then
    raise exception 'items of a locked rubric version cannot change' using errcode = '42501';
  end if;
  return coalesce(new, old);
end;
$$;

create trigger rubric_items_immutable before insert or update or delete on public.rubric_items
  for each row execute function public.rubric_items_immutable();

-- Publishing --------------------------------------------------------------------

-- Publishes a case version: locks its rubric version and makes it the case's current version.
-- Idempotent. Called by trusted server code (service role) only.
create function public.publish_case_version(p_case_version_id uuid)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v public.case_versions;
begin
  select * into v from public.case_versions where id = p_case_version_id for update;
  if not found then
    raise exception 'case version % not found', p_case_version_id using errcode = 'P0002';
  end if;
  if v.patient_view is null then
    raise exception 'case version % has no patient_view; generate it before publishing', p_case_version_id
      using errcode = '23514';
  end if;

  if v.published_at is null then
    update public.case_versions set published_at = now() where id = v.id;
  end if;
  update public.rubric_versions set locked_at = coalesce(locked_at, now()) where id = v.rubric_version_id;
  update public.cases
     set current_version_id = v.id,
         status = 'published',
         title = coalesce(v.content #>> '{meta,title}', title),
         difficulty = coalesce((v.content #>> '{meta,difficulty}')::smallint, difficulty)
   where id = v.case_id;
end;
$$;

-- Student-facing catalog. Deliberately runs with the owner's rights: students have no access to
-- case_versions (it holds the diagnosis), so this view exposes only safe, pre-station fields.
create view public.v_case_catalog as
select
  c.id,
  c.slug,
  c.title,
  c.difficulty,
  c.tags,
  s.slug as specialty_slug,
  s.name as specialty_name,
  s.colour_token as specialty_colour,
  cv.id as case_version_id,
  cv.content ->> 'candidate_brief' as candidate_brief,
  cv.content #>> '{patient,persona}' as persona,
  coalesce((cv.content #>> '{meta,station,history_seconds}')::int, 300) as history_seconds,
  coalesce((cv.content #>> '{meta,station,presentation_seconds}')::int, 180) as presentation_seconds,
  -- learning objectives are not exposed here: they usually name the diagnosis
  c.search
from public.cases c
join public.specialties s on s.id = c.specialty_id
join public.case_versions cv on cv.id = c.current_version_id
where c.status = 'published'
  and cv.published_at is not null
  and (c.organization_id is null or c.organization_id = public.auth_org())
  and auth.uid() is not null;
