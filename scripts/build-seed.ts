/**
 * Generates supabase/seed/05_levels.sql and supabase/seed/10_cases.sql from TypeScript sources of truth
 * (level maths, content/ case library). Usage:
 *   npm run seed:build          write files
 *   npm run seed:build -- --check   fail if files are out of date (CI)
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadCaseLibrary, type CompiledCase } from "../src/server/cases/library";
import { levelTitle, xpForLevel } from "../src/server/gamification/levels";

const ROOT = path.resolve(__dirname, "..");
const MAX_LEVEL = 60;
const HEADER = "-- GENERATED by scripts/build-seed.ts. Do not edit by hand; run `npm run seed:build`.\n";

// Deterministic UUID (v5-style, SHA-1 based) so re-running the seed is idempotent.
function uuid(name: string): string {
  const h = createHash("sha1").update(`crack-the-case:${name}`).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString("hex");
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const textArray = (a: string[]) => (a.length ? `array[${a.map(lit).join(", ")}]::text[]` : "'{}'::text[]");

function levelsSql(): string {
  const rows = Array.from({ length: MAX_LEVEL }, (_, i) => {
    const level = i + 1;
    return `  (${level}, ${lit(levelTitle(level))}, ${xpForLevel(level)})`;
  });
  return `${HEADER}
insert into public.levels (level, title, xp_required) values
${rows.join(",\n")}
on conflict (level) do update set title = excluded.title, xp_required = excluded.xp_required;
`;
}

function caseSql(c: CompiledCase): string {
  const slug = c.content.meta.slug;
  const rubricId = uuid(`rubric:${slug}`);
  const rubricVersionId = uuid(`rubric_version:${slug}:${c.rubricHash}`);
  const caseId = uuid(`case:${slug}`);
  const caseVersionId = uuid(`case_version:${slug}:${c.contentHash}:${c.rubricHash}`);
  const r = c.rubric;

  const items = r.items
    .map(
      (it, i) =>
        `  (${lit(uuid(`rubric_item:${rubricVersionId}:${it.key}`))}::uuid, ${lit(it.key)}, ${lit(it.domain)}::public.rubric_domain, ` +
        `${lit(it.label)}, ${it.description ? lit(it.description) : "null"}, ${it.max_points}, ${textArray(it.linked_fact_ids)}, ${it.is_critical}, ${i + 1})`,
    )
    .join(",\n");

  return `
-- ${slug} ------------------------------------------------------------
insert into public.rubrics (id, name, station_type)
values (${lit(rubricId)}, ${lit(r.name)}, ${lit(r.station_type)})
on conflict (id) do update set name = excluded.name;

-- A new rubric version is created only when the compiled rubric changes (id is derived from its hash).
insert into public.rubric_versions (id, rubric_id, version, domain_weights, global_rating_descriptors, examiner_question_bank, pass_mark)
select ${lit(rubricVersionId)}, ${lit(rubricId)},
       (select coalesce(max(version), 0) + 1 from public.rubric_versions where rubric_id = ${lit(rubricId)}),
       ${json(r.domain_weights)}, ${json(r.global_rating_descriptors)}, ${json(r.examiner_question_bank)}, ${r.pass_mark}
where not exists (select 1 from public.rubric_versions where id = ${lit(rubricVersionId)});

insert into public.rubric_items (id, key, domain, label, description, max_points, linked_fact_ids, is_critical, sort_order, rubric_version_id)
select v.*, ${lit(rubricVersionId)}::uuid from (values
${items}
) as v(id, key, domain, label, description, max_points, linked_fact_ids, is_critical, sort_order)
where not exists (select 1 from public.rubric_versions where id = ${lit(rubricVersionId)} and locked_at is not null)
on conflict (rubric_version_id, key) do nothing;

update public.rubrics set current_version_id = ${lit(rubricVersionId)} where id = ${lit(rubricId)};

insert into public.cases (id, slug, title, specialty_id, difficulty, tags)
values (${lit(caseId)}, ${lit(slug)}, ${lit(c.content.meta.title)},
        (select id from public.specialties where slug = ${lit(c.content.meta.specialty)}),
        ${c.content.meta.difficulty}, ${textArray(c.content.meta.tags)})
on conflict (slug) do update set specialty_id = excluded.specialty_id, tags = excluded.tags;

insert into public.case_versions (id, case_id, version, content, patient_view, rubric_version_id, content_hash)
select ${lit(caseVersionId)}, ${lit(caseId)},
       (select coalesce(max(version), 0) + 1 from public.case_versions where case_id = ${lit(caseId)}),
       ${json(c.content)}, ${json(c.patientView)}, ${lit(rubricVersionId)}, ${lit(c.contentHash)}
where not exists (select 1 from public.case_versions where id = ${lit(caseVersionId)});

do $$ begin perform public.publish_case_version(${lit(caseVersionId)}); end $$;
`;
}

function casesSql(cases: CompiledCase[]): string {
  const pending = cases.filter((c) => c.content.meta.review_status !== "clinician_reviewed").map((c) => c.content.meta.slug);
  const note = pending.length
    ? `-- NOTE: not yet clinician-reviewed (publish to students only after review): ${pending.join(", ")}\n`
    : "";
  return `${HEADER}${note}
begin;
${cases.map(caseSql).join("")}
commit;
`;
}

function main() {
  const check = process.argv.includes("--check");
  const outputs = {
    "supabase/seed/05_levels.sql": levelsSql(),
    "supabase/seed/10_cases.sql": casesSql(loadCaseLibrary(path.join(ROOT, "content"))),
  };

  let stale = false;
  for (const [rel, sql] of Object.entries(outputs)) {
    const file = path.join(ROOT, rel);
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (check) {
      if (current !== sql) {
        console.error(`✗ ${rel} is out of date. Run npm run seed:build`);
        stale = true;
      }
    } else if (current !== sql) {
      writeFileSync(file, sql);
      console.log(`✓ wrote ${rel}`);
    } else {
      console.log(`· ${rel} unchanged`);
    }
  }
  if (stale) process.exit(1);
}

main();
